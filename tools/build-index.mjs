#!/usr/bin/env node
// Writes the recipe tables into the root README from every recipe.yaml (feature 7).
//
//   npm run index           rewrite the block between the markers in README.md
//   npm run index:check     exit 1 if README.md is out of date (for CI)

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { checkManifest } from '../schema/manifest.mjs';
import { ALLOWLIST, loadTaxonomy, readAllowlistLines, recipeIds, root } from './recipes.mjs';

const START = '<!-- recipes:start (generated by `npm run index`; edit recipe.yaml files, not this block) -->';
const END = '<!-- recipes:end -->';
const LANE_ORDER = ['python', 'typescript', 'config', 'other'];

const taxonomy = loadTaxonomy();
const official = new Set(readAllowlistLines(readFileSync(join(root, ALLOWLIST), 'utf8')).map((l) => l.id));

const recipes = [];
for (const id of recipeIds()) {
  const { data, errors } = checkManifest(join(root, 'recipes', id, 'recipe.yaml'));
  if (errors.length > 0 || !data) {
    console.error(`recipes/${id}/recipe.yaml is invalid; run npm run validate first`);
    process.exit(1);
  }
  recipes.push({ id, ...data, official: data.tier === 'official' && official.has(id) });
}

const cell = (s) => String(s).replace(/\|/g, '\\|');
const label = (list, key) => taxonomy[list]?.[key]?.label ?? key;
const byTitle = (a, b) =>
  (a.status === 'deprecated') - (b.status === 'deprecated') || a.title.localeCompare(b.title);
const link = (r) => `[${cell(r.title)}](recipes/${r.id}/)${r.status === 'deprecated' ? ' (deprecated)' : ''}`;
const langLabel = (r) => (r.language === 'typescript' ? (r.variant === 'ts' ? 'TypeScript' : 'JavaScript') : label('languages', r.language));

function recipeTable(rows) {
  const lines = [
    '| Recipe | What runs the agent | Use case | ArmorIQ products | Shows | Tier |',
    '|---|---|---|---|---|---|',
  ];
  for (const r of rows.sort(byTitle)) {
    lines.push(
      `| ${link(r)}<br>${cell(r.summary)} | ${cell(label('frameworks', r.framework))} (${langLabel(r)}) | ${cell(
        label('use_cases', r.use_case),
      )} | ${r.products.map((p) => cell(label('products', p))).join(', ')} | ${
        (r.demonstrates ?? []).map((o) => cell(label('outcomes', o))).join(', ') || '·'
      } | ${r.official ? 'official' : 'community'} |`,
    );
  }
  return lines.join('\n');
}

function render() {
  const out = [START, ''];
  out.push(`${recipes.length} recipe${recipes.length === 1 ? '' : 's'}. Official recipes are maintained by ArmorIQ and tested live; community recipes are reviewed and pass the offline checks.`, '');

  out.push('### By language', '');
  const lanes = new Map();
  for (const r of recipes) {
    const lane = taxonomy.languages[r.language]?.lane ?? 'other';
    if (!lanes.has(lane)) lanes.set(lane, []);
    lanes.get(lane).push(r);
  }
  for (const lane of LANE_ORDER.filter((l) => lanes.has(l))) {
    const heading = lane === 'other' ? 'Other languages' : label('languages', lane);
    out.push(`#### ${heading}`, '', recipeTable(lanes.get(lane)), '');
  }

  out.push('### By what runs the agent', '');
  out.push('A framework, or the ArmorIQ SDK in a hand written loop, or the coding agent a plugin runs in.', '');
  out.push('| What runs the agent | Recipes |', '|---|---|');
  const frameworks = [...new Set(recipes.map((r) => r.framework))].sort((a, b) =>
    label('frameworks', a).localeCompare(label('frameworks', b)),
  );
  for (const f of frameworks) {
    const rows = recipes.filter((r) => r.framework === f).sort(byTitle);
    out.push(`| ${cell(label('frameworks', f))} | ${rows.map((r) => `${link(r)} (${langLabel(r)})`).join('<br>')} |`);
  }
  out.push('', END);
  return out.join('\n');
}

const readmePath = join(root, 'README.md');
const readme = readFileSync(readmePath, 'utf8');
const start = readme.indexOf(START.slice(0, 20));
const end = readme.indexOf(END);
if (start === -1 || end === -1 || end < start) {
  console.error(`README.md needs the markers:\n${START}\n${END}`);
  process.exit(1);
}
const next = readme.slice(0, start) + render() + readme.slice(end + END.length);

if (process.argv.includes('--check')) {
  if (next !== readme) {
    console.error('README.md recipe index is out of date; run npm run index and commit the result');
    process.exit(1);
  }
  console.log(`ok  README.md index is up to date (${recipes.length} recipes)`);
} else if (next === readme) {
  console.log(`ok  README.md index already up to date (${recipes.length} recipes)`);
} else {
  writeFileSync(readmePath, next);
  console.log(`wrote README.md index (${recipes.length} recipes)`);
}
